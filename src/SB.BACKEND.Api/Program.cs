using SB.BACKEND.Api;
using SB.BACKEND.Api.ExceptionHandling;
using SB.BACKEND.Application;
using SB.BACKEND.Infrastructure;
using SB.BACKEND.Services;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllers();
builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<GlobalExceptionHandler>();
builder.Services.AddHealthChecks();
builder.Services.AddApplication().AddInfrastructure().AddServices(builder.Configuration);
builder.Services.AddApiAuthentication(builder.Configuration).AddApiDocumentation();
var app = builder.Build();
app.UseExceptionHandler();
if (app.Environment.IsDevelopment()) { app.UseSwagger(); app.UseSwaggerUI(); }
app.UseHttpsRedirection();
app.UseAuthentication();
app.UseAuthorization();
app.MapControllers();
app.MapHealthChecks("/health").AllowAnonymous();
app.Run();
public partial class Program;
